def main():
    prs = load_template()
    P.course_cover(prs, title="受講データから見た設計の話",
                   subtitle="2026年上期レポート",
                   meta=["The Academy", "編集：コース設計チーム"])
    reset_to_cover_only(prs)

    used = render_all(prs, CONTENTS)

    add_back_cover(prs)
    finalize_page_numbers(prs, skip_first=True)
    prs.save(OUT)
    print(f"saved: {OUT} / slides: {len(prs.slides)}")
    print("\n----- 選ばれた構成 -----")
    for i, (name, _sig) in enumerate(used, start=2):
        print(f"P{i:>2} {name}")

    validate(prs, OUT, render=True)
    audit(prs)


if __name__ == "__main__":
    main()
